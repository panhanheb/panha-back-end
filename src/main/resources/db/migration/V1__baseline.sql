-- V1 baseline: the schema of the modules that exist today (users, catalog, cart, orders, audit).
-- Phase 3 replaces this with the full design in docs/DESIGN.md (variants, inventory, payments...). There
-- is no production data yet, so Phase 3 may rewrite this file; from the first deployment on, every change
-- is a new V<n>__*.sql file and existing files are never edited.
