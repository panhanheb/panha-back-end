-- =====================================================================================================
-- V2 (Phase 4, auth): refresh tokens. Only SHA-256 hashes are stored. Tokens of one sign-in share a
-- family_id; each refresh revokes the used token and links its successor (replaced_by_id), which is how
-- reuse of a stolen token is detected. The new roles (SUPER_ADMIN, SELLER, DELIVERY) are seeded by the
-- application on start, like the existing ones.
-- =====================================================================================================

CREATE TABLE refresh_tokens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash      VARCHAR(64)  NOT NULL,
    family_id       UUID         NOT NULL,
    session_version INTEGER      NOT NULL,
    expires_at      TIMESTAMPTZ  NOT NULL,
    revoked_at      TIMESTAMPTZ,
    replaced_by_id  BIGINT REFERENCES refresh_tokens (id) ON DELETE SET NULL,
    created_ip      VARCHAR(45),
    user_agent      VARCHAR(255),
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_refresh_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id) WHERE revoked_at IS NULL;
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_expires ON refresh_tokens (expires_at);
